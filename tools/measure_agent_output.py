#!/usr/bin/env python3
"""Measure Qew machine output against equivalent canonical GitHub JSON."""

import json
from pathlib import Path
import re
import sys
from typing import Dict, List, Tuple


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tests.command_harness import run_qew  # noqa: E402
from tests.test_prime_walk import issue as prime_issue  # noqa: E402
from tests.test_prime_walk import pages as prime_pages  # noqa: E402
from tests.test_prime_walk import prime_page  # noqa: E402
from tests.test_read_suite_walk import (  # noqa: E402
    blocker,
    issue as read_issue,
    issue_page,
    pages as read_pages,
    response,
    show_issue,
)
from tests.test_ready_walk import graph_response  # noqa: E402
from tests.test_ready_walk import issue as ready_issue  # noqa: E402


LEXICAL_TOKEN = re.compile(r"\w+|[^\w\s]", re.UNICODE)


def main() -> int:
    rows = []
    for name, github_response, arguments in _fixtures():
        result, _ = run_qew([github_response], arguments)
        if result.returncode != 0:
            print(f"{name} failed: {result.stderr}", file=sys.stderr)
            return 1
        raw = _canonical_github_output(github_response["stdout"])
        rows.append(_row(name, raw, result.stdout))
    print(_report(rows))
    return 0


def _fixtures() -> List[Tuple[str, Dict[str, str], List[str]]]:
    ready = graph_response(
        ready_issue(11, "Build queue"),
        ready_issue(12, "Deploy queue", assignees=1),
    )
    listed = read_pages(
        issue_page(
            read_issue(7, "Ready task", labels=["P1", "task", "qew:approved"]),
            read_issue(
                8,
                "Blocked task",
                labels=["P2", "task", "qew:approved"],
                blockers=[blocker(3, "Foundation", "OPEN")],
            ),
        )
    )
    prime = prime_pages(
        prime_page(
            prime_issue(2, "Ready work", ["P1", "task", "qew:approved"]),
            prime_issue(
                3,
                "Active work",
                ["P1", "task", "qew:approved", "in-progress"],
                assignees=["alexander"],
            ),
            prime_issue(
                4,
                "Blocked work",
                ["P2", "task", "qew:approved"],
                blockers=[8],
            ),
        )
    )
    shown = response(
        {"data": {"repository": {"issue": show_issue(12, approved=True)}}}
    )
    return [
        ("ready", {"stdout": json.dumps(ready)}, ["ready", "--repo", "acme/widgets", "--json"]),
        ("list", listed, ["list", "--repo", "acme/widgets", "--json"]),
        ("prime", prime, ["prime", "--repo", "acme/widgets", "--json"]),
        ("show", shown, ["show", "12", "--repo", "acme/widgets", "--json"]),
    ]


def _canonical_github_output(raw: str) -> str:
    return json.dumps(json.loads(raw), ensure_ascii=False, separators=(",", ":")) + "\n"


def _row(name: str, raw: str, qew: str) -> Dict[str, object]:
    raw_bytes = len(raw.encode("utf-8"))
    qew_bytes = len(qew.encode("utf-8"))
    raw_tokens = len(LEXICAL_TOKEN.findall(raw))
    qew_tokens = len(LEXICAL_TOKEN.findall(qew))
    return {
        "command": name,
        "raw_bytes": raw_bytes,
        "qew_bytes": qew_bytes,
        "byte_delta": _percent(qew_bytes, raw_bytes),
        "raw_tokens": raw_tokens,
        "qew_tokens": qew_tokens,
        "token_delta": _percent(qew_tokens, raw_tokens),
        "result": "win" if qew_tokens < raw_tokens else "regression" if qew_tokens > raw_tokens else "tie",
    }


def _percent(value: int, baseline: int) -> float:
    return round((value - baseline) * 100 / baseline, 1)


def _report(rows: List[Dict[str, object]]) -> str:
    lines = [
        "# Agent-output efficiency measurement",
        "",
        "Generated by `python3 tools/measure_agent_output.py` from the same fixed",
        "GitHub response fixtures used to drive the real Qew CLI. Raw values are",
        "canonical compact JSON for the equivalent GitHub query response; Qew values",
        "are exact `--json` stdout. Bytes are exact UTF-8 sizes. “Tokens” are a",
        "deterministic stdlib lexical proxy (`words + punctuation`), not a claim about",
        "any model-specific tokenizer. Negative deltas are wins.",
        "",
        "| Command | Raw bytes | Qew bytes | Byte Δ | Raw token proxy | Qew token proxy | Token Δ | Result |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for row in rows:
        lines.append(
            "| {command} | {raw_bytes} | {qew_bytes} | {byte_delta:+.1f}% | "
            "{raw_tokens} | {qew_tokens} | {token_delta:+.1f}% | {result} |".format(**row)
        )
    regressions = [str(row["command"]) for row in rows if row["result"] == "regression"]
    lines.extend(
        [
            "",
            "Regressions: " + (", ".join(regressions) if regressions else "none in this fixture set."),
            "",
            "The comparison measures transport/context volume only. It does not score",
            "semantic usefulness, API request cost, or latency.",
        ]
    )
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
